// Each character as GLYPH_HEIGHT rows of GLYPH_WIDTH bits, the leftmost dot the highest.
function parse(sheet) {
  const glyphs = new Map([[' ', new Array(GLYPH_HEIGHT).fill(0)]]);
  for (let band = 0; band < sheet.length; band += GLYPH_HEIGHT + 1) {
    const names = sheet[band];
    for (let at = 0; at < names.length; at += GLYPH_WIDTH + 1) {
      const rows = [];
      for (let r = 0; r < GLYPH_HEIGHT; r++) {
        const dots = sheet[band + 1 + r].slice(at, at + GLYPH_WIDTH);
        let bits = 0;
        for (let c = 0; c < GLYPH_WIDTH; c++) if (dots[c] === '#') bits |= 1 << (GLYPH_WIDTH - 1 - c);
        rows.push(bits);
      }
      glyphs.set(names[at], rows);
    }
  }
  return glyphs;
}

export const GLYPHS = parse(SHEET);

// The dots of `character`: its capital where there is no lower case of its own, and a
// question mark for anything the font does not have.
export const glyphOf = (character) => GLYPHS.get(character) ?? GLYPHS.get(character.toUpperCase()) ?? GLYPHS.get('?');

// Draws `text` on a 2D canvas context in its current fill style, the first character's
// top left dot at (x, y). Each dot is `dot` pixels ([across, down]: [1, 2] is double
// height), and characters stand `advance` dots apart.
export function drawText(ctx, text, x, y, { dot = [1, 1], advance = GLYPH_WIDTH + 1 } = {}) {
  const [w, h] = dot;
  let left = x;
  for (const character of text) {
    glyphOf(character).forEach((bits, r) => {
      // Runs of dots along a row are drawn as one rectangle.
      let c = 0;
      while (c < GLYPH_WIDTH) {
        if (!(bits & (1 << (GLYPH_WIDTH - 1 - c)))) {
          c += 1;
          continue;
        }
        const start = c;
        while (c < GLYPH_WIDTH && bits & (1 << (GLYPH_WIDTH - 1 - c))) c += 1;
        ctx.fillRect(left + start * w, y + r * h, (c - start) * w, h);
      }
    });
    left += advance * w;
  }
}
